const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('node:path');
const fs = require('node:fs');
(async()=>{
  let launch={headless:true};
  if(process.env.CHROMIUM_MODULE){const module=require(process.env.CHROMIUM_MODULE);const binary=module.default||module;launch={...launch,executablePath:await binary.executablePath(),args:binary.args};}
  const browser=await chromium.launch(launch);
  const errors=[];
  const c=await browser.newContext({viewport:{width:1440,height:1080}});
  const p=await c.newPage();p.on('pageerror',e=>errors.push(e.message));
  const base=process.env.LIFELINK_URL||'http://127.0.0.1:5173';
  const screenshots=process.env.SCREENSHOT_DIR||path.join(__dirname,'../../qa');fs.mkdirSync(screenshots,{recursive:true});
  await p.goto(base);await p.getByRole('heading',{name:/Find blood/}).waitFor();
  await p.waitForTimeout(2000);await p.screenshot({path:path.join(screenshots,'desktop.png'),fullPage:true});
  await p.goto(base+'/find');await p.getByRole('heading',{name:'Find a donor',exact:true}).waitFor();
  await p.waitForTimeout(700);await p.screenshot({path:path.join(screenshots,'finder.png'),fullPage:true});
  await p.goto(base+'/demo');await p.getByRole('button',{name:'Use this account'}).first().click();
  await p.getByRole('heading',{name:'Hello, Mira.'}).waitFor();
  await p.getByRole('link',{name:'Create request',exact:true}).click();
  await p.getByLabel('Patient initials / name (private)').fill('QA');
  await p.getByLabel('Hospital name (public)').fill('QA Showcase Hospital');
  const needed=new Date(Date.now()+86400000).toISOString().slice(0,16);
  await p.getByLabel('Needed by (your local time)').fill(needed);
  await p.getByRole('button',{name:'Publish request & find matches'}).click();
  const requestCard=p.locator('.dashboard-request').filter({hasText:'QA Showcase Hospital'});
  await requestCard.waitFor();
  if(await requestCard.getByRole('button',{name:'Private contact'}).count())throw new Error('Contact exposed before acceptance');
  const c2=await browser.newContext({viewport:{width:1280,height:900}});
  const donor=await c2.newPage();donor.on('pageerror',e=>errors.push(e.message));donor.on('dialog',dialog=>dialog.accept());
  await donor.goto(base+'/demo');await donor.getByRole('button',{name:'Use this account'}).nth(1).click();
  await donor.getByRole('heading',{name:'Hello, Aarav.'}).waitFor();
  await donor.locator('.dashboard-request').filter({hasText:'QA Showcase Hospital'}).getByRole('button',{name:'Accept',exact:true}).click();
  await requestCard.getByRole('button',{name:'Private contact'}).waitFor({timeout:15000});
  await requestCard.getByRole('button',{name:'Private contact'}).click();
  await p.getByRole('dialog').getByText('donor.opositive@demo.local',{exact:true}).waitFor();
  await p.screenshot({path:path.join(screenshots,'contact.png'),fullPage:true});
  await p.getByRole('button',{name:'Close dialog'}).click();
  p.on('dialog',dialog=>dialog.accept());
  await requestCard.getByRole('button',{name:'Mark fulfilled'}).click();
  await requestCard.locator('.status.fulfilled').waitFor();
  await p.goto(base+'/notifications');await p.getByRole('button',{name:'Mark all read'}).click();
  await p.goto(base+'/profile');await p.getByRole('button',{name:'Save profile'}).click();
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true});
  const m=await mobile.newPage();m.on('pageerror',e=>errors.push(e.message));
  await m.goto(base);await m.getByRole('heading',{name:/Find blood/}).waitFor();
  await m.screenshot({path:path.join(screenshots,'mobile.png'),fullPage:true});
  const overflow=await m.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  if(overflow)throw new Error('Mobile layout overflows horizontally');
  await m.getByRole('button',{name:'Toggle navigation'}).click();
  await m.getByRole('link',{name:'Find donors',exact:true}).click();
  await m.getByRole('heading',{name:'Find a donor',exact:true}).waitFor();
  await m.screenshot({path:path.join(screenshots,'mobile-finder.png'),fullPage:true});
  if(await m.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw new Error('Mobile finder overflows');
  await browser.close();
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('PASS: desktop/mobile, navigation, requester creation, separate donor session, acceptance, contact privacy, fulfilment, notifications and profile. No browser JS errors.');
})().catch(e=>{console.error(e);process.exit(1)});
